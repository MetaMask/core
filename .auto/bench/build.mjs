#!/usr/bin/env node
// Assembles .auto/bench/bundle.js for Hermes:
//   1. vendored bignumber.js 9.1.2 (defines global BigNumber in Hermes)
//   2. `const BigNumberJS = BigNumber;`
//   3. FROZEN reference implementation (.auto/bench/reference.impl.js) — the
//      original normalizeAmountString from origin/main at setup time, never
//      regenerated. Name: __referenceImpl.
//   4. CANDIDATE = the CURRENT production source
//      packages/assets-controller/src/utils/normalizeAmountString.ts,
//      transformed TS->JS (types stripped) so the bench always tracks the
//      live production file, never an independently edited clone.
//   5. driver (.auto/bench/driver.js): parity self-check (explicit suite +
//      seeded fuzz, every invocation) then the timed benchmark.
//
// Env: BENCH_MODE=bench (default) | sweep (scaling sweep timings).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const SRC = path.join(root, 'packages/assets-controller/src/utils/normalizeAmountString.ts');
const VENDOR = path.join(here, 'vendor/package/bignumber.js');
const REF = path.join(here, 'reference.impl.js');
const DRIVER = path.join(here, 'driver.js');
const OUT = path.join(here, 'bundle.js');
const FROZEN_TAG = '// FROZEN-REFERENCE';

function die(msg) {
  console.error('build failed: ' + msg);
  process.exit(1);
}

// --- transform the live production TS into plain JS -------------------------
const raw = fs.readFileSync(SRC, 'utf8');
const noImports = raw
  .replace(/^import[^\n]*;?\s*$/gm, '')
  .replace(/export\s+function\s+normalizeAmountString/, 'function normalizeAmountString')
  .replace(/export\s+const\s+normalizeAmountString/, 'const normalizeAmountString');
const transformed = ts.transpileModule(noImports, {
  compilerOptions: {
    target: ts.ScriptTarget.ES2019,
    module: ts.ModuleKind.ESNext,
  },
}).outputText;
// Strip any module boilerplate defensively; Hermes runs one plain script.
const candidate = transformed
  .split('\n')
  .filter((l) => !/^\s*(exports\.|Object\.defineProperty\(exports)/.test(l))
  .join('\n')
  .trim();
if (!/^(?:function|const) normalizeAmountString/m.test(candidate)) {
  die('could not locate function normalizeAmountString in transformed source');
}

// --- freeze the reference on first build -------------------------------------
if (!fs.existsSync(REF)) {
  // First build: production file IS the original. Freeze a renamed copy.
  const refSrc = candidate.replace(
    /^function normalizeAmountString/m,
    'function __referenceImpl',
  );
  fs.writeFileSync(
    REF,
    `${FROZEN_TAG} v1 — original normalizeAmountString from origin/main ` +
      `(abcfadf696b), frozen at setup. Do NOT edit or delete: parity anchor.\n` +
      refSrc + '\n',
  );
}
const reference = fs.readFileSync(REF, 'utf8');
if (!reference.startsWith(FROZEN_TAG) || !/^function __referenceImpl/m.test(reference)) {
  die('reference.impl.js is missing or corrupt — it is the immutable parity anchor');
}

const bn = fs.readFileSync(VENDOR, 'utf8');
const driver = fs.readFileSync(DRIVER, 'utf8');
const rawMode = process.env.BENCH_MODE;
const mode =
  rawMode === 'sweep' ? 'sweep' : rawMode === 'compare' ? 'compare' : 'bench';

const bundle = [
  '// GENERATED by .auto/bench/build.mjs — do not edit. Mode: ' + mode,
  'var BENCH_MODE = ' + JSON.stringify(mode) + ';',
  bn,
  'var BigNumberJS = BigNumber;',
  reference,
  candidate,
  driver,
].join('\n');

fs.writeFileSync(OUT, bundle);
console.log('bundle.js written (' + bundle.length + ' bytes, mode ' + mode + ')');
